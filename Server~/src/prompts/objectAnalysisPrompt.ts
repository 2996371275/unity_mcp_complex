/**
 * 注册物体分析提示词到MCP服务器
 */
export function registerObjectAnalysisPrompt(server: McpServer) {
  server.prompt(
    'unity_object_analysis_guide',
    '专门处理Unity物体分析和结构优化的智能助手',
    {
      analysisTarget: z.string().describe("分析目标描述"),
      analysisType: z.string().optional().describe("分析类型（基础/详细/性能/问题诊断等）"),
      sceneContext: z.string().optional().describe("当前场景上下文信息")
    },
    async ({ analysisTarget, analysisType, sceneContext }) => ({
      messages: [
        {
          role: 'user',
          content: {
            type: 'text',
            text: objectAnalysisPrompt
          }
        },
        {
          role: 'user', 
          content: {
            type: 'text',
            text: `用户分析需求: "${analysisTarget}"
${analysisType ? `分析类型: ${analysisType}` : ''}
${sceneContext ? `场景上下文: ${sceneContext}` : ''}

请根据上述指南，智能分析用户需求并使用 analyze_object 工具进行相应的物体分析。`
          }
        }
      ]
    })
  );
}

